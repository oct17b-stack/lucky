function check(year: number, rows: Row[]) {
  const listed = new Set(rows.map(([md]) => md));
  for (const [md, expected] of rows) {
    const [m, d] = md.split('-').map(Number) as [number, number];
    const r = thaiLunarDate(year, m, d);
    assert.equal(formatThaiLunar(r), expected, `${year}-${md}`);
    assert.equal(r.holyDay, true, `${year}-${md} 应为วันพระ`);
  }
  // 反向检查：全年其他日期都不是 วันพระ
  for (let t = Date.UTC(year, 0, 1); t < Date.UTC(year + 1, 0, 1); t += 86_400_000) {
    const dt = new Date(t);
    const md = `${String(dt.getUTCMonth() + 1).padStart(2, '0')}-${String(dt.getUTCDate()).padStart(2, '0')}`;
    if (!listed.has(md)) assert.equal(thaiLunarDate(year, dt.getUTCMonth() + 1, dt.getUTCDate()).holyDay, false, `${year}-${md} 不应为วันพระ`);
  }
}

