test('每个阴历月 29 或 30 天，日期连续（1902–2098 抽样）', () => {
  let prev = thaiLunarDate(1950, 1, 1);
  for (let t = Date.UTC(1950, 0, 2); t < Date.UTC(1956, 0, 1); t += 86_400_000) {
    const d = new Date(t);
    const cur = thaiLunarDate(d.getUTCFullYear(), d.getUTCMonth() + 1, d.getUTCDate());
    const prevIndex = (prev.waxing ? 0 : 15) + prev.day;
    const curIndex = (cur.waxing ? 0 : 15) + cur.day;
    if (curIndex !== 1) assert.equal(curIndex, prevIndex + 1, d.toISOString());
    else assert.equal(prevIndex, prev.monthLength, `上个月应在第 ${prev.monthLength} 天结束`);
    prev = cur;
  }
});

test('กาลโยค：与 2565–2569 年公开历书一致（0 = 星期日）', () => {
  // พ.ศ. 2565（จ.ศ. 1384）：ธงชัย พุธ、อธิบดี อังคาร、อุบาทว์ อังคาร、โลกาวินาศ พฤหัส
  assert.deepEqual(kalaYok(2022, 6, 1), { cs: 1384, thongchai: 3, athibodi: 2, ubat: 2, lokawinat: 4 });
  // พ.ศ. 2567：ธงชัย อังคาร、อธิบดี พฤหัส、อุบาทว์ จันทร์、โลกาวินาศ เสาร์
  assert.deepEqual(kalaYok(2024, 6, 1), { cs: 1386, thongchai: 2, athibodi: 4, ubat: 1, lokawinat: 6 });
  // พ.ศ. 2568：ธงชัย ศุกร์、อธิบดี ศุกร์、โลกาวินาศ อาทิตย์
  const k2568 = kalaYok(2025, 6, 1);
  assert.deepEqual([k2568.thongchai, k2568.athibodi, k2568.lokawinat], [5, 5, 0]);
  // พ.ศ. 2569：ธงชัย จันทร์、อธิบดี เสาร์
  const k2569 = kalaYok(2026, 5, 1);
  assert.deepEqual([k2569.thongchai, k2569.athibodi], [1, 6]);
  // 4 月 15 日仍属上一个จ.ศ.
  assert.equal(kalaYok(2026, 4, 15).cs, 1387);
  assert.equal(kalaYok(2026, 4, 16).cs, 1388);
  // 2025-06-06 是星期五：พ.ศ. 2568 的ธงชัย和อธิบดี都是星期五（PPTV 公布）
  assert.deepEqual(auspiciousDaysOf(2025, 6, 6), ['thongchai', 'athibodi']);
});
